function ReproduceAllCombinedFigures(panelFolder, outputFolder)
% ReproduceAllCombinedFigures  Assemble all six multi-panel manuscript figures
% from the single-panel .fig files in panelFolder (defaults to PaperResults/).
%
% Figures produced (both .fig and .pdf, plus lowercase/Arial edited versions):
%   1. CombinedClassesABCD
%   2. ProbabilityCombined
%   3. EffectiveCombined
%   4. FittnesCombined
%   5. SCCombined2
%   6. DeltaMuCDEF

    repoRoot = fileparts(fileparts(mfilename('fullpath')));
    addpath(genpath(repoRoot));

    if nargin < 1 || isempty(panelFolder)
        panelFolder = fullfile(repoRoot, 'PaperResults');
    end
    if nargin < 2 || isempty(outputFolder)
        outputFolder = fullfile(repoRoot, 'CombinedFigures');
    end
    if ~exist(outputFolder, 'dir')
        mkdir(outputFolder);
    end

    % 1. CombinedClassesABCD (2x2: A, B, C, D)
    combineFourPanels({ ...
        fullfile(panelFolder, 'Number_of_Classes.fig'), ...
        fullfile(panelFolder, 'Number_of_Classes_Y.fig'), ...
        fullfile(panelFolder, 'Classified_Population_Proportion.fig'), ...
        fullfile(panelFolder, 'Classified_Proportion_Y.fig')}, ...
        fullfile(outputFolder, 'CombinedClassesABCD'), ...
        {'A', 'B', 'C', 'D'});

    % 2. ProbabilityCombined (1x2: A, B)
    combineTwoPanels( ...
        fullfile(panelFolder, 'Probability_Y2.fig'), ...
        fullfile(panelFolder, 'Proportion_of_Identical_SLFs_Y.fig'), ...
        fullfile(outputFolder, 'ProbabilityCombined'), ...
        {'A', 'B'});

    % 3. EffectiveCombined (1x2: A, B)
    combineTwoPanels( ...
        fullfile(panelFolder, 'Effective_Number_of_Distinct_Haplotypes.fig'), ...
        fullfile(panelFolder, 'Effective_Number_Y.fig'), ...
        fullfile(outputFolder, 'EffectiveCombined'), ...
        {'A', 'B'});

    % 4. FittnesCombined (1x2: A, B)
    combineTwoPanels( ...
        fullfile(panelFolder, 'Fitness_Y_Low.fig'), ...
        fullfile(panelFolder, 'Fitness_Y_High.fig'), ...
        fullfile(outputFolder, 'FittnesCombined'), ...
        {'A', 'B'});

    % 5. SCCombined2 (1x2: A, B)
    combineTwoPanels( ...
        fullfile(panelFolder, 'Proportion_of_SC_Haplotypes.fig'), ...
        fullfile(panelFolder, 'ProportionByRateSC.fig'), ...
        fullfile(outputFolder, 'SCCombined2'), ...
        {'A', 'B'});

    % 6. DeltaMuCDEF (2x2: C, D, E, F)
    combineFourPanels({ ...
        fullfile(panelFolder, 'Mutation_of_mu_g.fig'), ...
        fullfile(panelFolder, 'Population_Mean_mu_g.fig'), ...
        fullfile(panelFolder, 'Neutral_mu_g_of_Haplotypes.fig'), ...
        fullfile(panelFolder, '_mu_g_of_Haplotypes.fig')}, ...
        fullfile(outputFolder, 'DeltaMuCDEF'), ...
        {'C', 'D', 'E', 'F'});

    % Post-processing: lowercase panel labels & Arial axis labels
    figNames = {'CombinedClassesABCD', 'ProbabilityCombined', ...
                'EffectiveCombined', 'FittnesCombined', ...
                'SCCombined2', 'DeltaMuCDEF'};
    lowercaseDir = fullfile(outputFolder, 'edited_figures');
    for k = 1:numel(figNames)
        convert_fig_letters(fullfile(outputFolder, [figNames{k} '.fig']), lowercaseDir);
        fixAxisLabelsFontAndSave(fullfile(lowercaseDir, [figNames{k} '.fig']));
    end
end

